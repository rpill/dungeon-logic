import { existsSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
function assert(condition,message){if(!condition)throw new Error(message);}
const root=resolve(fileURLToPath(new URL('..',import.meta.url)));
const scenePath=resolve(root,'src/scenes/MasteryScene.ts');
const main=readFileSync(resolve(root,'src/main.ts'),'utf8');
assert(existsSync(scenePath),'MasteryScene must exist.');
assert(main.includes('MasteryScene'),'MasteryScene must be registered in main.ts.');
const scene=readFileSync(scenePath,'utf8');
const progress=readFileSync(resolve(root,'src/ui/UiProgressBar.ts'),'utf8');
assert(scene.includes('createUiSceneHeader'),'MasteryScene must use the shared UI scene header.');
assert(scene.includes('createMasterySeal'),'MasteryScene must render the labyrinth seal.');
assert(scene.includes('createMasteryRequirementPanel'),'Mastery requirements must use the shared slate shell.');
assert(scene.includes('createMasteryRequirementRowPanel'),'Mastery requirements must use runtime row components.');
assert(scene.includes('const rowGap = rowHeight + (narrow ? 8 : 10)'),'Requirement rows must keep a positive vertical gap.');
assert(scene.includes("case 'campaign':")&&scene.includes("case 'daily-completed':")&&scene.includes("case 'endless-completed':"),'MasteryScene must render all three requirement types.');
assert(scene.includes('MASTERY_RANK_IDS'),'MasteryScene must render the full rank path.');
assert(scene.includes('const sealX = centerX;')&&scene.includes('compact ? 158 : 190'),'Narrow Mastery hero must center the emblem and compact its rank copy on short viewports.');
assert(scene.includes('? copy.mastery.maxRank'),'Maximum Mastery rank must show maximum-rank copy.');
assert(scene.includes('UI_ICON_KEYS.lock'),'Future mastery ranks must use lock icons.');
assert(scene.includes('const isPast = index < currentIndex;')&&scene.includes('const isFuture = index > currentIndex;'),'Rank track must distinguish completed and future ranks.');
assert(scene.includes("const isMaster = rank === 'MASTER';"),'Rank track must handle MASTER separately.');
assert(scene.includes('masteryOpen'),'MasteryScene must emit mastery_open analytics once.');
assert(!/\bXP\b|experience points|очки опыта/i.test(scene),'MasteryScene must not contain XP language.');
assert(!/statistics|статистик/i.test(scene),'MasteryScene must not become a statistics dashboard.');
assert(scene.includes('const valueX = barRight;'),'Requirement counter must align with the right edge of the progress bar.');
assert(scene.includes('this.add.image(iconX, y, iconKey)'),'Requirement icon must be vertically centered in the row.');
assert(scene.includes('width * 0.88'),'Requirement rows must remain narrower than the shell.');
assert(scene.includes('createUiProgressBar(this, {'),'Requirement progress must use the shared UI progress bar.');
assert(progress.includes('scene.textures.createCanvas'),'Shared progress fill must retain the canvas-gradient strategy.');
assert(progress.includes('UI_THEME.colors.semantic.gold')&&progress.includes('UI_THEME.colors.semantic.success'),'Shared progress must use semantic gold-to-success colors.');
assert(!scene.includes("fontSize: narrow ? (rank === 'MASTER' ? '7px' : '9px')"),'Rank-track labels must respect the 10px typography floor.');
console.info('[Dungeon Logic] Mastery scene sanity: PASS');
